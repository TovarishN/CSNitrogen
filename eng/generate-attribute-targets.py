"""Generate independently selectable global-target spelling modules.
Unicode identifiers ignore @, escapes and formatting under their selected policy.
"""
import json
import re
from pathlib import Path
root=Path(__file__).resolve().parents[1]
q=json.dumps

def spellings(c):
    digits=' '.join("['%s' '%s']"%(d,d.upper()) if d in 'abcdef' else q(d) for d in f'{ord(c):04x}')
    return '('+q(c)+' / "\\\\u" '+digits+' / "\\\\U0000" '+digits+')'
def ranges(values):
    result=[];lo=hi=values[0]
    for value in values[1:]+[0x10001]:
        if value==hi+1:hi=value;continue
        a="'\\u%04x'"%lo;b="'\\u%04x'"%hi
        result.append(a if lo==hi else a+'..'+b);lo=hi=value
    return '['+' '.join(result)+']'
current=json.loads((root/'docs/coverage/unicode-data.json').read_text())
current['format']=json.loads((root/'tests/Corpus/attribute-target-formatting.json').read_text())['format']
historical=json.loads((root/'docs/coverage/historical-unicode-data.json').read_text())
for label,data in [('Current',current),('Historical',historical)]:
    lines=['// Generated by eng/generate-attribute-targets.py. Unicode notices: docs/coverage/sources/Unicode3/LICENSE.txt.',
           f'syntax module CSharp.GlobalTargets{label}', '{',
           ' token TargetPart = '+ranges(data['part'])+';',
           ' token TargetFormat = '+' / '.join(spellings(chr(n)) for n in data['format'])+';']
    words=[' '.join(spellings(c)+' TargetFormat*' for c in word) for word in ('assembly','module')]
    lines+=[' token TargetToken = "@"? ('+' / '.join(words)+') !(TargetPart / CSharp.Lexical.UnicodePart);',
            f' extend syntax CSharp.Attributes.GlobalAttributeTarget {{ | {label}GlobalTarget = Value:TargetToken }}','}']
    (root/f'src/CSNitrogen.Syntax/Grammars/GlobalTargets{label}.ngr').write_text('\n'.join(lines)+'\n')
path=root/'src/CSNitrogen.Syntax/Grammars/Attributes.ngr';source=path.read_text()
keywords=re.findall(r'"([a-z]+)"',(root/'docs/coverage/reserved-keywords.txt').read_text())
block='// BEGIN GENERATED ATTRIBUTE TARGETS\n extensible syntax GlobalAttributeTarget {}\n syntax AttributeTarget = CSharp.Lexical.Identifier / '+' / '.join(q(w) for w in keywords)+';\n // END GENERATED ATTRIBUTE TARGETS'
source=re.sub(r'// BEGIN GENERATED ATTRIBUTE TARGETS.*?// END GENERATED ATTRIBUTE TARGETS',lambda _:block,source,flags=re.S)
path.write_text(source)
