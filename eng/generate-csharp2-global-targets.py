"""Generate versioned normalized global-target tokens using Unicode4 format data."""
import argparse
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'docs/coverage/csharp2-unicode-data.json').read_text())
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--profile',choices=['CSharp2','CSharp3'],default='CSharp2')
profile=parser.parse_args().profile
label='Second' if profile=='CSharp2' else 'Third'
q=json.dumps
def spelling(c):
 n=ord(c)
 def hexes(n,width):return ' '.join("['"+d+"' '"+d.upper()+"']" if d in 'abcdef' else q(d) for d in f'{n:0{width}x}')
 if n<=65535:return '('+q(c)+' / "\\\\u" '+hexes(n,4)+' / "\\\\U0000" '+hexes(n,4)+')'
 high=0xd800+((n-0x10000)>>10);low=0xdc00+((n-0x10000)&1023)
 return f"(['\\u{high:04x}'] ['\\u{low:04x}'] / "+'"\\\\U" '+hexes(n,8)+')'
lines=['// Generated by eng/generate-csharp2-global-targets.py; Unicode4 license in docs/coverage/sources/Unicode4/LICENSE.txt.', 'syntax module CSharp.GlobalTargets'+label,'{',' token TargetFormat = '+' / '.join(spelling(chr(n)) for n in data['format'])+';']
if profile=='CSharp3':lines[0]=lines[0].replace('.py;', '.py --profile CSharp3;')
words=[' '.join(spelling(c)+' TargetFormat*' for c in word) for word in ['assembly','module']]
lines += [' token TargetToken = "@"? ('+' / '.join(words)+') !(CSharp.Lexical.IdPart / CSharp.Lexical.ScalarPart / CSharp.Lexical.UnicodePart);',' extend syntax CSharp.Attributes.GlobalAttributeTarget { | '+label+'GlobalTarget = Value:TargetToken'+(' | SecondUnknownGlobalTarget = !TargetToken Value:CSharp.Attributes.AttributeTarget &(":" (CSharp.Attributes.Attribute; ",")+ ","? "]" (CSharp.Attributes.GlobalAttributeSection+ / "namespace" / !.))' if profile=='CSharp2' else '')+' }','}']
(root/f'src/CSNitrogen.Syntax/Grammars/GlobalTargets{label}.ngr').write_text('\n'.join(lines)+'\n')
