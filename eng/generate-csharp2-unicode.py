"""Generate scalar CSharp2 categories from the pinned Unicode 4.0 database."""
import hashlib,json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
source=root/'docs/coverage/sources/Unicode4'
p=json.loads((source/'provenance.json').read_text())
raw=(source/'UnicodeData-4.0.0.txt').read_bytes()
assert hashlib.sha256(raw).hexdigest()==p['dataSha256']
categories={};first=None
for line in raw.decode().splitlines():
 f=line.split(';');n=int(f[0],16)
 if f[1].endswith(', First>'):first=n
 elif f[1].endswith(', Last>'):
  assert first is not None
  categories.update((k,f[2]) for k in range(first,n+1));first=None
 else:categories[n]=f[2]
assert first is None
start={95}|{n for n,c in categories.items() if c in ['Lu','Ll','Lt','Lm','Lo','Nl']}
data=dict(version=p['version'],sourceSha256=p['dataSha256'],start=sorted(start),part=sorted(start|{n for n,c in categories.items() if c in ['Nd','Pc','Mn','Mc','Cf']}),format=sorted(n for n,c in categories.items() if c=='Cf'),space=sorted(n for n,c in categories.items() if c=='Zs'))
(root/'docs/coverage/csharp2-unicode-data.json').write_text(json.dumps(data,separators=(',',':'))+'\n')
def ranges(items):
 result=[];lo=hi=items[0]
 for n in items[1:]+[0x110001]:
  if n==hi+1:hi=n;continue
  result.extend([lo,hi]);lo=hi=n
 return ','.join('0x%X'%n for n in result)
lines=['// Generated by eng/generate-csharp2-unicode.py; see docs/coverage/sources/Unicode4/LICENSE.txt.', 'namespace CSNitrogen.Parsing;', 'internal static class CSharp2UnicodeTables','{']
for name in ['start','part','format','space']:
 lines += [f'    private static readonly int[] {name}Ranges = [{ranges(data[name])}];',f'    internal static bool Is{name.title()}(int value) => Contains({name}Ranges,value);']
lines += ['    private static bool Contains(int[] ranges,int value)','    {','        int low=0,high=ranges.Length/2-1;','        while(low<=high)','        {','            int middle=(low+high)/2;','            if(value<ranges[middle*2])high=middle-1;','            else if(value>ranges[middle*2+1])low=middle+1;','            else return true;','        }','        return false;','    }','}']
(root/'src/CSNitrogen/Parsing/CSharp2UnicodeTables.g.cs').write_text('\n'.join(lines)+'\n')
