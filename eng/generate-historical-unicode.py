"""Generate BMP C# categories from the pinned original Unicode 3.0 database.
First/Last records represent inclusive ranges. Preserve the source and license.
"""
import hashlib
import json
import re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = root / 'docs/coverage/sources/Unicode3'
raw = (source / 'UnicodeData-3.0.0.txt').read_bytes()
provenance = json.loads((source / 'provenance.json').read_text())
assert hashlib.sha256(raw).hexdigest() == provenance['dataSha256']
categories = {}
first = None
for line in raw.decode().splitlines():
    fields = line.split(';'); code = int(fields[0], 16)
    if fields[1].endswith(', First>'):
        assert first is None
        first = code
    elif fields[1].endswith(', Last>'):
        assert first is not None
        for item in range(first, min(code, 65535) + 1): categories[item] = fields[2]
        first = None
    elif code <= 65535: categories[code] = fields[2]
assert first is None
start = sorted({95} | {n for n,c in categories.items() if c in ['Lu','Ll','Lt','Lm','Lo','Nl']})
part = sorted(set(start) | {n for n,c in categories.items() if c in ['Nd','Pc','Mn','Mc','Cf']})
data = dict(version='3.0.0', sourceSha256=provenance['dataSha256'], start=start, part=part,
            format=sorted(n for n,c in categories.items() if c=='Cf'), space=sorted(n for n,c in categories.items() if c=='Zs'))
(root/'docs/coverage/historical-unicode-data.json').write_text(json.dumps(data,separators=(',',':'))+'\n')
def ranges(items):
    result=[]; lo=hi=items[0]
    for item in items[1:]+[0x10001]:
        if item==hi+1: hi=item; continue
        result.extend([lo,hi]);lo=hi=item
    return ','.join('0x%04X'%n for n in result)
lines=['// Generated by eng/generate-historical-unicode.py. Unicode data: see docs/coverage/sources/Unicode3/LICENSE.txt.',
       'namespace CSNitrogen.Parsing;', 'internal static class HistoricalUnicodeTables', '{']
for name in ['start','part','format','space']:
    lines += [f'    private static readonly int[] {name}Ranges = [{ranges(data[name])}];',
              f'    internal static bool Is{name.title()}(char value) => Contains({name}Ranges,value);']
lines += ['    private static bool Contains(int[] ranges,char value)', '    {',
          '        int low=0,high=ranges.Length/2-1;', '        while(low<=high)', '        {',
          '            int middle=(low+high)/2;', '            if(value<ranges[middle*2])high=middle-1;',
          '            else if(value>ranges[middle*2+1])low=middle+1;', '            else return true;',
          '        }', '        return false;', '    }', '}']
(root/'src/CSNitrogen/Parsing/HistoricalUnicodeTables.g.cs').write_text('\n'.join(lines)+'\n')
