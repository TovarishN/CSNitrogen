"""Generate Nitride project files from src/CSNitrogen.Syntax/nitrogen.json.

nitrogen.json stays the source of truth for the Nitrogen generator. Nitride's
workspace (nitride.nproj) includes one folder per language holding exactly one
.nproj; each lists the same ordered grammars and start rule. --check verifies
the checked-in files are current without writing.
"""
import argparse
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
syntax = root / 'src/CSNitrogen.Syntax'
languages = syntax / 'Languages'
header = '// Generated by eng/generate-nitride-projects.py from src/CSNitrogen.Syntax/nitrogen.json.\n'


def extension(name):
    return '.' + name.lower()


def project(language):
    lines = [header + f'language {language["name"]}', '{', f'  extensions {extension(language["name"])};']
    lines += [f'  grammar ../../{grammar};' for grammar in language['grammars']]
    lines += [f'  start {language["start"]};', '', '  nitrogen', '  {',
              f'    namespace {language["namespace"]};', '  }', '}']
    return '\n'.join(lines) + '\n'


def expected():
    manifest = json.loads((syntax / 'nitrogen.json').read_text())
    files = {}
    for language in manifest['languages']:
        files[languages / language['name'] / f'{language["name"]}.nproj'] = project(language)
    includes = '\n'.join(f'  include {(languages / l["name"]).relative_to(root).as_posix()};'
                         for l in manifest['languages'])
    files[root / 'nitride.nproj'] = header + 'workspace\n{\n' + includes + '\n}\n'
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = expected()
    present = set(languages.glob('*/*.nproj')) if languages.exists() else set()
    stale = sorted(str(p.relative_to(root)) for p in present - files.keys())
    changed = sorted(str(p.relative_to(root)) for p, text in files.items()
                     if not p.exists() or p.read_text() != text)
    if args.check:
        for path in changed + stale:
            print(f'stale: {path}', file=sys.stderr)
        return 1 if changed or stale else 0
    for path in stale:
        (root / path).unlink()
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
